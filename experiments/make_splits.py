"""Write the canonical problem splits, as explicit ID lists, for every script and for coding_eval/.

Why
---
Before 2026-11-21, splits were redrawn at load time (seed-0 shuffle, dev then test), and coding_eval/ had its own
HumanEval+ split (seed 2026, 20/40) that overlapped ours. Also, the strength sweep tuned on dev problems the probe
had been trained on. This script freezes one set of splits, with a third split, `tune`, kept apart from both:

    dev    train probes (and anything else fitted to data)
    tune   choose layer / strength / other hyperparameters
    test   held out; touched only by final runs

The old seed-0 rule is reproduced exactly, so every existing result stays inside the split it was run on:

    GSM8K (1319)       dev = perm[:200] (unchanged)   test = perm[200:500] (unchanged)   tune = perm[500:600] (new)
    HumanEval+ (163)   dev = old dev[:32] (the 32 the baseline ran)   tune = old dev[32:64]   test = old test (99)

Outputs
-------
    configs/splits.json          {benchmark: {dev: [ids], tune: [ids], test: [ids]}}   read by reasoning_env.load_benchmark
    coding_eval/data/splits.json HumanEval+ in coding_eval's format: development = dev + tune, held_out = test

Run
---
    python experiments/make_splits.py
"""
import json
import random
from pathlib import Path

from datasets import load_dataset

ROOT = Path(__file__).resolve().parent.parent
HUMANEVALPLUS_BROKEN = {"HumanEval/32"}  # same exclusion as src/reasoning_env.py


def legacy_perm(ids, seed=0):
    """The pre-2026-11-21 split rule: shuffle the problem list with random.Random(seed)."""
    perm = list(range(len(ids)))
    random.Random(seed).shuffle(perm)
    return [ids[i] for i in perm]


def main():
    gsm = legacy_perm([f"gsm8k/{i}" for i in range(len(load_dataset("openai/gsm8k", "main", split="test")))])
    he = legacy_perm([r["task_id"] for r in load_dataset("evalplus/humanevalplus", split="test")
                      if r["task_id"] not in HUMANEVALPLUS_BROKEN])
    splits = {
        "gsm8k": {"dev": gsm[:200], "tune": gsm[500:600], "test": gsm[200:500]},
        "humanevalplus": {"dev": he[:32], "tune": he[32:64], "test": he[64:163]},
    }
    for name, s in splits.items():
        all_ids = s["dev"] + s["tune"] + s["test"]
        assert len(all_ids) == len(set(all_ids)), f"{name}: splits overlap"
    # Existing committed results must stay inside the split they were run on.
    for path, bench, split in [("output/baseline/baseline/gsm8k_dev.jsonl", "gsm8k", "dev"),
                               ("output/baseline/baseline/humanevalplus_dev.jsonl", "humanevalplus", "dev"),
                               ("output/inputs/gsm8k_test.jsonl", "gsm8k", "test"),
                               ("output/inputs/humanevalplus_test.jsonl", "humanevalplus", "test")]:
        ids = [json.loads(line)["id"] for line in open(ROOT / path)]
        assert set(ids) <= set(splits[bench][split]), f"{path} is not inside {bench}/{split}"

    json.dump(dict(note="Canonical splits; generated by experiments/make_splits.py. Do not edit by hand.", **splits),
              open(ROOT / "configs/splits.json", "w"), indent=2)
    he_s = splits["humanevalplus"]
    json.dump({"benchmark": "HumanEval+", "source": "configs/splits.json (experiments/make_splits.py)",
               "development": he_s["dev"] + he_s["tune"], "held_out": he_s["test"]},
              open(ROOT / "coding_eval/data/splits.json", "w"), indent=2)
    for name, s in splits.items():
        print(name, {k: len(v) for k, v in s.items()})


if __name__ == "__main__":
    main()
